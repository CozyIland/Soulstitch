export function drawShape(name,x,y,size,f,col,acc,flash){
  const sc=size/50;ctx.save();ctx.translate(x,y);ctx.scale(sc*f,sc);ctx.lineJoin='round';
  const sh=ctx.createLinearGradient(-20,-50,20,50);sh.addColorStop(0,'rgba(255,255,255,.3)');sh.addColorStop(1,'rgba(0,0,0,.42)');
  for(const s of SHAPES[name])for(const mm of s.m?[1,-1]:[1]){
    ctx.save();ctx.scale(mm,1);
    if(s.t==='s'){if(!flash){ctx.strokeStyle=OUT;ctx.lineWidth=LW*.7/sc;ctx.stroke(s.p)}}
    else{
      ctx.fillStyle=flash?'#fff':s.t==='c'?acc:s.t==='w'?'#f4ecd8':s.t==='k'?'#140e10':col;
      if(s.t==='c'&&!flash){ctx.shadowColor=acc;ctx.shadowBlur=12}
      ctx.fill(s.p,'evenodd');ctx.shadowBlur=0;
      if(!flash&&(s.t==='a'||s.t==='b')){ctx.fillStyle=sh;ctx.fill(s.p);if(s.t==='b'){ctx.fillStyle='rgba(0,0,0,.3)';ctx.fill(s.p)}}
      ctx.strokeStyle=OUT;ctx.lineWidth=LW*1.15/sc;ctx.stroke(s.p);
    }
    ctx.restore();
  }
  ctx.restore();
}
